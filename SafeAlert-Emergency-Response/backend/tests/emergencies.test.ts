test('authenticated idempotent submission returns one authoritative incident under concurrent retries',async()=>{
  const key=randomUUID(),data=body();
  const responses=await Promise.all([1,2].map(()=>request(app).post('/api/emergencies').set(auth(userToken)).set('Idempotency-Key',key).send(data)));
  assert.deepEqual(responses.map(r=>r.status).sort(),[200,201]);assert.equal(responses[0].body.data.id,responses[1].body.data.id);
  assert.equal(await Emergency.countDocuments({userId,idempotencyKey:key}),1);
  assert.equal(responses[0].body.data.requestHash,undefined);assert.equal(responses[0].body.data.user.passwordHash,undefined);
  await request(app).post('/api/emergencies').set(auth(userToken)).set('Idempotency-Key',key).send({...data,notes:'Changed request'}).expect(409);
  const other=await request(app).post('/api/emergencies').set(auth(otherUserToken)).set('Idempotency-Key',key).send(data).expect(201);
  assert.notEqual(other.body.data.id,responses[0].body.data.id);
});
