import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import mongoose from 'mongoose';
import { env } from './config/environment.ts';
import authRoutes from './routes/authRoutes.ts';
import adminRoutes from './routes/adminRoutes.ts';
import emergencyRoutes from './routes/emergencyRoutes.ts';
import bleRoutes from './routes/bleRoutes.ts';
import uploadRoutes from './routes/uploadRoutes.ts';
import { locationRoutes,responderRoutes } from './routes/locationRoutes.ts';
import operationsRoutes from './routes/operationsRoutes.ts';
import notificationRoutes from './routes/notificationRoutes.ts';
import mapRoutes from './routes/mapRoutes.ts';
import diagnosticRoutes from './routes/diagnosticRoutes.ts';
import { requestIdMiddleware } from './middleware/requestIdMiddleware.ts';
import { errorHandler } from './middleware/errorHandler.ts';
import { ApiError,success } from './shared/http.ts';
import { pushConfigured } from './services/notifications.ts';
const app=express();app.disable('x-powered-by');
// Configure only a known reverse-proxy hop count; never trust arbitrary forwarded IPs.
if(process.env.TRUST_PROXY_HOPS)app.set('trust proxy',Number(process.env.TRUST_PROXY_HOPS));
app.use(requestIdMiddleware,helmet());
const origins=env.ALLOWED_ORIGINS.split(',').map(v=>v.trim());
app.use(cors({origin:(origin,callback)=>!origin||origins.includes(origin)?callback(null,true):callback(new ApiError(403,'ORIGIN_NOT_ALLOWED','Origin is not allowed.')),credentials:true,exposedHeaders:['x-request-id']}));
app.use(express.json({limit:'256kb'}));
app.use((req,res,next)=>{const started=performance.now();res.on('finish',()=>{if(env.NODE_ENV!=='test')console.info(JSON.stringify({level:'info',event:'http',requestId:req.id,method:req.method,status:res.statusCode,durationMs:Math.round(performance.now()-started)}));});next();});
app.get('/health',(req,res)=>success(res,{status:'ok'}));
app.get('/ready',(_req,res)=>{
  const database=mongoose.connection.readyState===1;
  const dependencies={database,push:pushConfigured(),facilities:Boolean(process.env.OVERPASS_URL),routing:Boolean(process.env.ROUTING_URL)};
  const ready=database&&(env.NODE_ENV!=='production'||Object.values(dependencies).every(Boolean));
  return success(res,{ready,dependencies},ready?200:503);
});
app.use('/api/auth',authRoutes);
app.use('/api/admin',adminRoutes,operationsRoutes);
app.use('/api/emergencies',emergencyRoutes);
app.use('/api/locations',locationRoutes);
app.use('/api/responders',responderRoutes);
app.use('/api/user',bleRoutes);
app.use('/api/upload',uploadRoutes);
app.use('/api/notifications',notificationRoutes);
app.use('/api/diagnostics',diagnosticRoutes);
app.use('/api',mapRoutes);
app.use((_req,_res,next)=>next(new ApiError(404,'NOT_FOUND','Endpoint not found.')));
app.use(errorHandler);
export default app;
